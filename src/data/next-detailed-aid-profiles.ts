export function nextProfile(
  key: string,
  meta: WordMorph,
  meaning: string,
): AidProfile | undefined {
  let p =
    forms[meta.lemma] ||
    specializedProfiles[meta.lemma] ||
    lemmaProfiles[meta.lemma] ||
    roots[meta.root];
  if (!p && !noRootShortcut.has(meta.root)) p = rootProfiles[meta.root];
  const verse = key.split(":").slice(0, 2).join(":");
  if (carefulAyahs.has(verse) || theologicalLemmas.has(meta.lemma)) {
    if (!p)
      p = {
        kind: "meaning",
        anchor: `বর্তমান শব্দার্থ: ${meaning}`,
        explanation: `এই জায়গায় শব্দটির অর্থ «${meaning}»; পূর্ণ বক্তব্য যাকারিয়ার অনুবাদ অনুযায়ী রাখুন।`,
        picture:
          "শব্দের লেখা, অর্থ ও আয়াতের পাশের শব্দের সম্পর্ক দিয়ে মনে রাখুন।",
      };
    return {
      ...p,
      picture:
        meta.root === "klf"
          ? p.picture
          : `«${meaning}» অর্থটি উচ্চারণের সঙ্গে রাখুন এবং আয়াতের পাশের শব্দ দিয়ে বাক্যের সম্পর্ক মিলিয়ে পড়ুন।`,
      caution:
        meta.root === "klf"
          ? p.caution
          : theologicalLemmas.has(meta.lemma) ||
              ["krs", "wjh", "Alh"].includes(meta.root)
            ? (p.caution ? p.caution + " " : "") +
              "আল্লাহর নাম, সিফাত ও কাজের ক্ষেত্রে মানুষের সঙ্গে তুলনা বা কল্পিত আকৃতি ব্যবহার করবেন না; সহায়িকা কোনো নিজস্ব তাফসীর যোগ করছে না।"
            : p.caution,
    };
  }
  return p;
}

